// 诊断日志：驱动跑在 UMDF 宿主里，出错时没有控制台也没有调试器，
// 把关键返回值写进文件是唯一能在本机看清「哪一步失败」的办法。
static void PocketDeskLog(const char* format, ...)
{
    char buffer[1024];
    va_list args;
    va_start(args, format);
    vsnprintf_s(buffer, sizeof(buffer), _TRUNCATE, format, args);
    va_end(args);

    FILE* file = nullptr;
    char windowsDirectory[MAX_PATH] = {};
    char logPath[MAX_PATH] = {};
    const auto count = GetWindowsDirectoryA(windowsDirectory, MAX_PATH);
    if (count == 0 || count >= MAX_PATH) return;
    if (sprintf_s(logPath, "%s\\Temp\\PocketDeskIdd.log", windowsDirectory) < 0) return;
    if (fopen_s(&file, logPath, "a") == 0 && file != nullptr)
    {
        SYSTEMTIME now;
        GetLocalTime(&now);
        fprintf(file, "%04d-%02d-%02d %02d:%02d:%02d %s\n",
                now.wYear, now.wMonth, now.wDay, now.wHour, now.wMinute, now.wSecond, buffer);
        fclose(file);
    }
}

