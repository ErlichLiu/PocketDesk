// 手机屏的档位在 Spec 中定义，两套比例各一档：
//   前一半是手机竖屏（540:950），后一半是折叠屏展开（2248:2480，OPPO Find N5 内屏）。
// 第 0 档是首选：Windows 建屏时用它，也就是 1080×1900、200% 缩放。
// 应用层按设备形态选档（ScreenProfile），跨比例换档会让 UU 重新推流，这是预期行为。
static std::vector<ScreenMode> PocketDeskModes()
{
    std::vector<ScreenMode> modes;
    const size_t perProfile = (Spec::MaxWidth - Spec::BaseWidth) / Spec::Step + 1;
    modes.reserve(perProfile * 2);

    for (size_t i = 0; i < perProfile; i++)
    {
        const DWORD width = Spec::BaseWidth + static_cast<DWORD>(i) * Spec::Step;
        modes.push_back({ width, Spec::Height(width), Spec::VSync });
    }
    for (size_t i = 0; i < perProfile; i++)
    {
        const DWORD width = Spec::BaseWidth + static_cast<DWORD>(i) * Spec::Step;
        modes.push_back({ width, Spec::FoldHeight(width), Spec::VSync });
    }
    return modes;
}

